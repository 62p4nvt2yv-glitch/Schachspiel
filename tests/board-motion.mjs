import assert from 'node:assert/strict';
import {Chess} from 'chess.js';
import {planBoardMotion,squarePosition} from '../lib/board-motion.ts';

const snapshot=game=>({fen:game.fen(),history:game.history()});
const game=new Chess();
let before=snapshot(game);game.move('e4');
assert.deepEqual(planBoardMotion(before,game).figures,[{from:'e2',to:'e4',type:'p',color:'w'}]);
assert.equal(planBoardMotion(snapshot(game),game),null);
game.undo();assert.equal(planBoardMotion(before,game),null);
for(const san of ['e4','e5','Nf3','Nc6','Bc4','Nf6'])game.move(san);
before=snapshot(game);game.move('O-O');
assert.deepEqual(planBoardMotion(before,game).figures.map(m=>[m.from,m.to]),[['e1','g1'],['h1','f1']]);
const ep=new Chess();for(const san of ['e4','a6','e5','d5'])ep.move(san);
before=snapshot(ep);ep.move('exd6');
assert.deepEqual(planBoardMotion(before,ep).captured,{square:'d5',type:'p',color:'b'});
const capture=new Chess();for(const san of ['e4','d5'])capture.move(san);
before=snapshot(capture);capture.move('exd5');
assert.equal(planBoardMotion(before,capture).captured.square,'d5');
const promotion=new Chess('7k/P7/8/8/8/8/8/7K w - - 0 1');
before=snapshot(promotion);promotion.move({from:'a7',to:'a8',promotion:'n'});
assert.equal(planBoardMotion(before,promotion).figures[0].type,'p');
assert.equal(promotion.get('a8').type,'n');
const restored=new Chess();restored.loadPgn(game.pgn());
assert.equal(planBoardMotion(snapshot(new Chess()),restored),null);
assert.deepEqual(squarePosition('a8',false),{x:0,y:0});
assert.deepEqual(squarePosition('a8',true),{x:7,y:7});
assert.deepEqual(squarePosition('e2',true),{x:3,y:1});
console.log('BESTANDEN: Gleitbewegung, Rochade, Schlagen, en passant, Umwandlung, Rücknahme, Wiederherstellung und gedrehtes Brett.');
